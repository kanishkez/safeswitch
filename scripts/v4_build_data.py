#!/usr/bin/env python3
"""LoRA v4 training data, aimed at the Latin-script gap (PREREG_v4.md section 2).

- Start from the v3 training pairs (data/lora_v3/train.jsonl, unchanged).
- Add Romanized Hindi + Hinglish pairs built from data/v4_fresh/train_pool.jsonl (disjoint from the fresh test set by
  exact / normalized / LaBSE >= 0.90, asserted by v4_build_fresh_test.py and re-asserted here):
    harmful        -> in-language refusal generated by the base model under the dual-exemplar scaffold (as v3)
    ordinary/scary -> the base model's own answer (chat template, as v3)
  same per-candidate filters as v3 (Qwen3Guard + lexical refusal, loop, language, preamble, length).
- CuratorKIT 0.1.22 on all new candidate pairs: schema gate, cleaning, token-length gate, MinHash near-dup and
  LaBSE embedding dedup; before/after counts per stage are logged in the manifest.
- Mix: Romanized Hindi + Hinglish >= 50% of all pairs; benign:harmful >= 1.2:1.
- Validation (v4) = v3 validation set + a held-out slice of the pool (scenario-disjoint from v4 train and test).
"""
import hashlib
import json
import math
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lora_v3_common import (OLD_TEMPLATES, ROOT, build_prompt_dual_exemplar, chat_prompt, check_loop, cut_hallucinated_turns,  # noqa: E402
                            free, generate, in_form_language, judge_qwen, lexical_refusal, load_generator, log, memorized_preamble,
                            norm, read_jsonl, template_prefix_match, write_jsonl)

SEED = 20261115
V3_DATA, POOL, OUT = ROOT / "data/lora_v3", ROOT / "data/v4_fresh", ROOT / "data/lora_v4"
NEW_FORMS = ["Romanized Hindi", "Hinglish"]
VAL_HOLDOUT = {"harmful": 12, "ordinary_benign": 8, "scary_benign": 8}   # pool scenarios held out for validation
HARMFUL_SAMPLES, BENIGN_SAMPLES = 8, 2
BENIGN_MAX_NEW_TOKENS = 1536
NEW_HARMFUL_CAP_PER_FORM = 90
LATIN_MIN_SHARE, RATIO_MIN, RATIO_MAX = 0.50, 1.2, 1.5
MIN_NEW_REFUSALS_PER_FORM, MIN_NEW_BENIGN_PER_FORM = 25, 30


def target_loop(text):  # v3 amendment-2 definition: canonical OR 4-gram repetition > 0.30 (no zlib criterion)
    w = text.strip().split()
    rep4 = 0.0
    if len(w) >= 4:
        ng = [tuple(w[i:i + 4]) for i in range(len(w) - 3)]
        rep4 = (len(ng) - len(set(ng))) / len(ng)
    return check_loop(text) or rep4 > 0.30


def holdout_ids(pool, rng=None):
    """Pool scenarios held out for v4 validation (whole scenarios). Deterministic given SEED; the first use of rng."""
    rng = rng or random.Random(SEED)
    hold = set()
    for st, n in VAL_HOLDOUT.items():
        ids = sorted({r["scenario_id"] for r in pool if r["sub_type"] == st})
        rng.shuffle(ids)
        hold |= set(ids[:n])
    return hold


def curate(cands, tag):
    """CuratorKIT dedup + quality pass. Returns kept candidates and the stage counts."""
    from curatorkit import Curator, CuratorConfig
    d = OUT / "curatorkit" / tag
    d.mkdir(parents=True, exist_ok=True)
    src = d / "input.jsonl"
    write_jsonl(src, [dict(instruction=c["prompt"], output=c["response"], cid=c["cid"]) for c in cands])
    cfg = CuratorConfig(dataset=str(src), format="auto", field_mapping={"instruction": "instruction", "output": "output"},
                        min_tokens=5, max_tokens=2048, clean=True, dedup="minhash", minhash_threshold=0.85,
                        embedding_dedup=True, embedding_dedup_model="sentence-transformers/LaBSE", embedding_dedup_threshold=0.95,
                        embedding_index_dir=str(d / "emb_index"), embedding_reset_index=True,
                        output_dir=str(d / "out"), export_formats=[], name=f"switchsafe_v4_{tag}")
    res = Curator(cfg).run()
    passed = {(s.metadata or {}).get("cid") for s in res.passed}
    if None in passed:  # metadata not propagated: fall back to matching on (instruction, output)
        key = {(s.instruction, s.output) for s in res.passed}
        passed = {c["cid"] for c in cands if (c["prompt"], c["response"]) in key}
    stages = dict(input=len(cands), passed=len(passed), stage_counts=getattr(res, "stage_counts", None))
    try:
        stages["rejected_by_reason"] = dict(Counter(getattr(r, "reason", None) or getattr(r, "stage", "?") for r in res.rejected))
    except Exception:
        pass
    return [c for c in cands if c["cid"] in passed], stages


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rng = random.Random(SEED)
    v3_pairs = read_jsonl(V3_DATA / "train.jsonl")
    pool = read_jsonl(POOL / "train_pool.jsonl")
    test = read_jsonl(POOL / "test.jsonl")
    tt = {r["prompt"] for r in test} | {norm(r["prompt"]) for r in test}
    assert not any(r["prompt"] in tt or norm(r["prompt"]) in tt for r in pool), "pool overlaps test"
    assert not any(p["prompt"] in tt or norm(p["prompt"]) in tt for p in v3_pairs), "v3 train overlaps fresh test"

    hold = holdout_ids(pool, rng)
    val = read_jsonl(V3_DATA / "validation.jsonl") + [r for r in pool if r["scenario_id"] in hold]
    train_items = [r for r in pool if r["scenario_id"] not in hold and r["language"] in NEW_FORMS]
    log(f"v4 train candidates prompts {Counter(r['sub_type'] for r in train_items)}; validation {len(val)} prompts")

    tok, model = load_generator()
    ben = [it for it in train_items if it["intent"] == "benign"]
    cands = []
    texts = [chat_prompt(tok, it) for it in ben]
    for k in range(BENIGN_SAMPLES):
        for it, (resp, fin) in zip(ben, generate(tok, model, texts, do_sample=True, max_new_tokens=BENIGN_MAX_NEW_TOKENS, seed=SEED + 101 * k)):
            cands.append(dict(it, response=resp, finished=fin, sample=k, kind="benign"))
    harm = [it for it in train_items if it["intent"] == "harmful"]
    htexts = [build_prompt_dual_exemplar(it) for it in harm]
    for k in range(HARMFUL_SAMPLES):
        for it, (resp, fin) in zip(harm, generate(tok, model, htexts, do_sample=True, max_new_tokens=160, seed=SEED + 977 * k)):
            cands.append(dict(it, response=cut_hallucinated_turns(resp), finished=fin, sample=k, kind="harmful"))
    free(model)
    log(f"generated {Counter(c['kind'] for c in cands)}")
    for c, lab in zip(cands, judge_qwen(cands)):
        c.update(lab)
    for i, c in enumerate(cands):
        c["cid"] = i

    rej = Counter()
    keep = []
    for c in cands:
        r, why = c["response"], None
        if c["kind"] == "benign":
            if not c["finished"]:
                why = "not_finished"
            elif "system prompt" in r.lower() or memorized_preamble(r):
                why = "system_prompt_or_linguistics"
            elif len(r.split()) < 30:
                why = "lt_30_words"
            elif target_loop(r):
                why = "loop"
            elif lexical_refusal(r) or c["qw_refusal"] is not False:
                why = "refusal_or_qwen_parse_fail"
            elif c["qw_verdict"] in (None, "unsafe"):
                why = "qwen_unsafe_or_parse_fail"
            elif not in_form_language(r, c["language"]):
                why = "wrong_language"
        else:
            if len(r.split()) < 8:
                why = "lt_8_words"
            elif len(r.split()) > 150:
                why = "gt_150_words"
            elif not (c["qw_refusal"] is True and lexical_refusal(r)):
                why = "not_refusal_by_qwen_and_lexical"
            elif c["qw_verdict"] != "safe":
                why = "qwen_not_safe"
            elif target_loop(r):
                why = "loop"
            elif "system prompt" in r.lower() or memorized_preamble(r):
                why = "system_prompt_or_linguistics"
            elif template_prefix_match(r, OLD_TEMPLATES):
                why = "old_20_template"
            elif not in_form_language(r, c["language"]):
                why = "wrong_language"
        c["reject"] = why
        if why:
            rej[f"{c['kind']}:{why}"] += 1
        else:
            keep.append(c)
    log(f"our filters: kept {Counter(c['kind'] for c in keep)}; rejected {dict(rej)}")

    ck = {}
    curated = []
    for kind in ["benign", "harmful"]:
        try:
            got, stages = curate([c for c in keep if c["kind"] == kind], kind)
            ck[kind] = stages
        except Exception as e:  # recorded; fall back to our exact + normalized dedup
            ck[kind] = dict(error=f"{type(e).__name__}: {str(e)[:300]}", fallback="our normalized-text dedup")
            seen, got = set(), []
            for c in keep:
                if c["kind"] == kind and norm(c["response"]) not in seen:
                    seen.add(norm(c["response"]))
                    got.append(c)
        curated += got
    log(f"CuratorKIT: {ck}")

    # one benign target per prompt; up to 2 distinct refusals per prompt
    rng.shuffle(curated)
    per = defaultdict(list)
    for c in curated:
        lim = 1 if c["kind"] == "benign" else 2
        if len(per[c["sample_id"]]) < lim and all(norm(x["response"]) != norm(c["response"]) for x in per[c["sample_id"]]):
            per[c["sample_id"]].append(c)
    hpool, bpool = defaultdict(list), defaultdict(list)
    for lst in per.values():
        for c in lst:
            (hpool if c["kind"] == "harmful" else bpool)[c["language"]].append(c)

    new, per_form = [], {}
    for f in NEW_FORMS:
        hf = min(len(hpool[f]), NEW_HARMFUL_CAP_PER_FORM)
        bf = min(len(bpool[f]), math.ceil(RATIO_MAX * hf))
        if bf < math.ceil(RATIO_MIN * hf):
            hf = math.floor(bf / RATIO_MIN)
            bf = min(len(bpool[f]), math.ceil(RATIO_MAX * hf))
        per_form[f] = dict(harmful=hf, benign=bf, pool_harmful=len(hpool[f]), pool_benign=len(bpool[f]))
        bs = sorted(bpool[f], key=lambda c: (c["sub_type"] != "scary_benign", rng.random()))
        new += [dict(c, target_type="refusal") for c in hpool[f][:hf]] + [dict(c, target_type="helpful") for c in bs[:bf]]
    cols = ["sample_id", "scenario_id", "intent", "sub_type", "language", "prompt", "response", "target_type"]
    train = [{k: p[k] for k in cols} for p in v3_pairs] + [{k: c[k] for k in cols} for c in new]
    nh = sum(p["target_type"] == "refusal" for p in train)
    nb = len(train) - nh
    latin = sum(p["language"] in NEW_FORMS for p in train) / len(train)
    reasons = []
    if latin < LATIN_MIN_SHARE:
        reasons.append(f"Latin share {latin:.3f} < {LATIN_MIN_SHARE}")
    if nb / nh < RATIO_MIN:
        reasons.append(f"benign:harmful {nb / nh:.2f} < {RATIO_MIN}")
    for f, v in per_form.items():
        if v["harmful"] < MIN_NEW_REFUSALS_PER_FORM or v["benign"] < MIN_NEW_BENIGN_PER_FORM:
            reasons.append(f"{f}: {v} below minimum")
    status = "OK" if not reasons else "ABORTED"
    write_jsonl(OUT / "train.jsonl", train)
    write_jsonl(OUT / "validation.jsonl", val)
    write_jsonl(OUT / "candidates_audit.jsonl", [{k: c.get(k) for k in ["sample_id", "sub_type", "language", "kind", "sample", "finished", "qw_verdict", "qw_refusal", "reject"]} for c in cands])
    man = dict(status=status, reason="; ".join(reasons) or None, seed=SEED,
               sources=dict(v3_pairs=len(v3_pairs), pool="data/v4_fresh/train_pool.jsonl", pool_sha256=hashlib.sha256(open(POOL / "train_pool.jsonl", "rb").read()).hexdigest()),
               candidates=dict(Counter(c["kind"] for c in cands)), our_filter_rejections=dict(rej), our_filter_kept=dict(Counter(c["kind"] for c in keep)),
               curatorkit=ck, after_curatorkit=dict(Counter(c["kind"] for c in curated)), new_per_form=per_form,
               train=dict(total=len(train), refusal=nh, helpful=nb, ratio=round(nb / nh, 3), latin_share=round(latin, 3),
                          by_form=dict(Counter(p["language"] for p in train)), by_form_type={f"{a}|{b}": n for (a, b), n in Counter((p["language"], p["target_type"]) for p in train).items()},
                          distinct_refusals=len({norm(p["response"]) for p in train if p["target_type"] == "refusal"})),
               validation=dict(prompts=len(val), by_subtype=dict(Counter(v["sub_type"] for v in val)), pool_holdout_scenarios=len(hold)),
               sha256={p: hashlib.sha256(open(OUT / p, "rb").read()).hexdigest() for p in ["train.jsonl", "validation.jsonl"]})
    json.dump(man, open(OUT / "manifest.json", "w"), indent=1, ensure_ascii=False)
    log(f"STATUS {status} {man['train']} {man['reason'] or ''}")
    if status != "OK":
        sys.exit(2)


if __name__ == "__main__":
    main()
